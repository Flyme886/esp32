#!/usr/bin/env python3
"""Turn the pictures and the laugh in assets/source/ into firmware headers.

    wa1.png    level 1 (the starting baby)
    wa2.png    level 2
    wa3.png    level 3 (the big laugh)
    oops.png   shown when a baby lands on a different one ("轻松绷住")
    block1.png, block2.png, block3.png
               troublemakers: they turn up at random, never merge, and trigger 轻松绷住
    laugh.wav  looped while level 3 is on screen
               (or laugh.mp4 / .mov / .mp3: seconds 1-4 are cut out, needs ffmpeg)
    oops.wav   played with the 熊大 picture
               (or oops.mp4 / .mov / .mp3: seconds 3-4.5 are cut out, needs ffmpeg)

Run from the pin-hao-wa folder:

    python3 tools/build_assets.py

It writes src/assets/sprites.h, src/assets/laugh.h and src/assets/oops_sound.h. Both are committed, so you
only need to run this again after changing a picture or the laugh.

Requires: pillow, numpy, scipy (optional) and ffmpeg (only for mp3 or video input).
"""
from pathlib import Path
import shutil
import subprocess
import sys
import wave

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LOCAL = ROOT / "assets" / "source"
OUT = ROOT / "src" / "assets"

KEY = 0xF81F                 # transparent colour in RGB565
ICON = 40                    # board tile size (pixels)
BIG = 120                    # celebration picture size
OOPS = 112                   # "轻松绷住" picture size
LAUGH_RATE = 16000
LAUGH_MAX_S = 4.0
VIDEO_CUT = (1.0, 4.0)       # laugh from a video or mp3: use seconds 1-4 of it
OOPS_CUT = (3.0, 4.5)        # 轻松绷住 sound from a video or mp3: seconds 3-4.5


def rgb565(r, g, b):
    v = ((int(r) & 0xF8) << 8) | ((int(g) & 0xFC) << 3) | (int(b) >> 3)
    return KEY ^ 0x0020 if v == KEY else v


def cut_out(path):
    """Remove the plain white background by flood-filling from the borders."""
    im = Image.open(path).convert("RGB")
    a = np.asarray(im).astype(int)
    near_white = (a.min(-1) > 228) & ((a.max(-1) - a.min(-1)) < 24)
    h, w = near_white.shape
    bg = np.zeros_like(near_white)
    stack = [(y, x) for y in range(h) for x in (0, w - 1)] + [(y, x) for x in range(w) for y in (0, h - 1)]
    while stack:
        y, x = stack.pop()
        if bg[y, x] or not near_white[y, x]:
            continue
        bg[y, x] = True
        if y > 0: stack.append((y - 1, x))
        if y < h - 1: stack.append((y + 1, x))
        if x > 0: stack.append((y, x - 1))
        if x < w - 1: stack.append((y, x + 1))
    fg = ~bg
    try:                                   # keep only the biggest blob (drops stray specks)
        from scipy import ndimage
        lab, n = ndimage.label(fg)
        if n > 1:
            sizes = ndimage.sum(fg, lab, range(1, n + 1))
            fg = lab == (int(np.argmax(sizes)) + 1)
    except ImportError:
        pass
    alpha = fg.astype(np.uint8) * 255
    rgba = np.dstack([np.asarray(im), alpha])
    ys, xs = np.where(alpha > 0)
    return Image.fromarray(rgba, "RGBA").crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))


def fit(img, size):
    s = size / max(img.width, img.height)
    small = img.resize((max(1, round(img.width * s)), max(1, round(img.height * s))), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(small, ((size - small.width) // 2, size - small.height), small)
    return canvas


def to_array(name, img):
    a = np.asarray(img)
    vals = [KEY if px[3] < 128 else rgb565(px[0], px[1], px[2]) for row in a for px in row]
    lines = [f"static const uint16_t {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), 16):
        lines.append("  " + ", ".join(f"0x{v:04X}" for v in vals[i:i + 16]) + ",")
    lines.append("};")
    return lines


def rounded_square(path, size, radius, top_bias=0.5):
    """Square crop with rounded corners. top_bias < 0.5 keeps more of the top of a tall picture (faces)."""
    im = Image.open(path).convert("RGB")
    side = min(im.size)
    x0 = (im.width - side) // 2
    y0 = int((im.height - side) * top_bias)
    im = im.crop((x0, y0, x0 + side, y0 + side)).resize((size, size), Image.LANCZOS)
    mask = Image.new("L", (size, size), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=255)
    out = im.convert("RGBA")
    out.putalpha(mask)
    return out


def build_sprites():
    files = [LOCAL / f"wa{i}.png" for i in (1, 2, 3)] + [LOCAL / "oops.png"] + \
            [LOCAL / f"block{i}.png" for i in (1, 2, 3)]
    missing = [f.name for f in files if not f.exists()]
    if missing:
        sys.exit("missing in assets/source: " + ", ".join(missing))
    lines = ["#pragma once", "#include <stdint.h>",
             "// Generated by tools/build_assets.py from assets/source/*.png.",
             f"#define WA_ICON {ICON}", f"#define WA_BIG {BIG}", f"#define WA_OOPS {OOPS}",
             f"#define WA_KEY 0x{KEY:04X}", ""]
    cuts = [cut_out(f) for f in files[:3]]
    for i, c in enumerate(cuts, 1):
        lines += to_array(f"wa_icon_{i}", fit(c, ICON))
    lines += to_array("wa_big_3", fit(cuts[2], BIG))
    lines += to_array("wa_oops", rounded_square(files[3], OOPS, 14))
    for i, f in enumerate(files[4:], 1):
        lines += to_array(f"wa_block_{i}", rounded_square(f, ICON, 9, top_bias=0.2))
    lines.append("// levels 1-3, then the three troublemakers (4-6)")
    lines.append("static const uint16_t* const wa_icons[6] = {wa_icon_1, wa_icon_2, wa_icon_3, wa_block_1, wa_block_2, wa_block_3};")
    (OUT / "sprites.h").write_text("\n".join(lines) + "\n")
    print("wrote src/assets/sprites.h")


def read_audio(path, cut=VIDEO_CUT):
    if path.suffix.lower() == ".wav":
        with wave.open(str(path)) as w:
            sr, ch, sw = w.getframerate(), w.getnchannels(), w.getsampwidth()
            raw = w.readframes(w.getnframes())
        if sw != 2:
            sys.exit("laugh.wav must be 16-bit PCM (or give an mp3 and install ffmpeg)")
        x = np.frombuffer(raw, dtype=np.int16).astype(float).reshape(-1, ch).mean(1)
    else:
        if not shutil.which("ffmpeg"):
            sys.exit("ffmpeg is needed for mp3/mp4 (brew install ffmpeg), or use the ready-cut laugh.wav")
        start, end = cut
        out = subprocess.run(["ffmpeg", "-v", "error", "-ss", str(start), "-t", str(end - start), "-i", str(path),
                              "-vn", "-ac", "1", "-ar", str(LAUGH_RATE), "-f", "s16le", "-"],
                             capture_output=True, check=True).stdout
        return np.frombuffer(out, dtype=np.int16).astype(float)
    n = int(len(x) * LAUGH_RATE / sr)                    # simple resample
    return np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x)


def trim_for_loop(x):
    """Drop leading/trailing silence and fade the ends so the laugh loops without a gap or a pop."""
    frame = LAUGH_RATE // 100
    rms = np.array([np.sqrt(np.mean(x[i:i + frame] ** 2)) for i in range(0, len(x) - frame, frame)])
    loud = np.where(rms > rms.max() * 0.08)[0]
    if len(loud):
        x = x[loud[0] * frame:(loud[-1] + 1) * frame]
    fade = int(0.015 * LAUGH_RATE)
    ramp = np.linspace(0, 1, fade)
    x = x.copy()
    x[:fade] *= ramp
    x[-fade:] *= ramp[::-1]
    return x


def write_laugh(x, path, note, name="laugh_pcm", rate_macro="LAUGH_RATE"):
    x = x[: int(LAUGH_MAX_S * LAUGH_RATE)]
    peak = np.abs(x).max() or 1
    x = np.clip(np.round(x / peak * 26000), -32768, 32767).astype(int)
    lines = ["#pragma once", "#include <stdint.h>", f"// {note}",
             f"#define {rate_macro} {LAUGH_RATE}", f"static const int16_t {name}[{len(x)}] = {{"]
    for i in range(0, len(x), 24):
        lines.append("  " + ", ".join(str(v) for v in x[i:i + 24]) + ",")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n")
    print("wrote", path.relative_to(ROOT), f"({len(x) / LAUGH_RATE:.1f} s)")


def build_laugh():
    for name in ("laugh.wav", "laugh.mp3", "laugh.mp4", "laugh.mov", "laugh.m4a"):
        p = LOCAL / name
        if p.exists():
            write_laugh(trim_for_loop(read_audio(p)), OUT / "laugh.h",
                        f"Generated by tools/build_assets.py from assets/source/{name}.")
            return
    sys.exit("missing in assets/source: laugh.wav (or laugh.mp4 / .mov / .mp3)")


def build_oops_sound():
    for name in ("oops.wav", "oops.mp3", "oops.mp4", "oops.mov", "oops.m4a"):
        p = LOCAL / name
        if p.exists():
            x = read_audio(p, OOPS_CUT)
            fade = int(0.01 * LAUGH_RATE)
            x = x.copy()
            x[:fade] *= np.linspace(0, 1, fade)
            x[-fade:] *= np.linspace(1, 0, fade)
            write_laugh(x, OUT / "oops_sound.h", f"Generated by tools/build_assets.py from assets/source/{name}.",
                        name="oops_pcm", rate_macro="OOPS_RATE")
            return
    sys.exit("missing in assets/source: oops.wav (or oops.mp4 / .mov / .mp3)")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    build_sprites()
    build_laugh()
    build_oops_sound()
